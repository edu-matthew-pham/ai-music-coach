# --- the 24 browsing keys --------------------------------------


def test_there_are_24_browsing_keys_each_major_beside_its_minor():
    keys = browse_keys()

    assert len(keys) == 24
    assert len({value for _label, value in keys}) == 24

    assert [label for label, _ in keys[:6]] == [
        "C major", "A minor", "G major", "E minor", "D major", "B minor"
    ]


def test_a_minor_key_uses_its_relative_majors_notes_with_its_own_home():
    assert parse_browse_key("C major") == ("C", "C")
    assert parse_browse_key("A minor") == ("C", "A")
    assert parse_browse_key("E minor") == ("G", "E")
    assert parse_browse_key("Bb minor") == ("Db", "Bb")

    with pytest.raises(ValueError):
        parse_browse_key("H major")


# Written by hand: the chords a beginner expects in each key.
KEY_CHORDS_BY_HAND = {
    "C major": ["C", "Dm", "Em", "F", "G", "Am", "Bdim"],
    "A minor": ["Am", "Bdim", "C", "Dm", "Em", "F", "G"],
    "G major": ["G", "Am", "Bm", "C", "D", "Em", "F#dim"],
    "E minor": ["Em", "F#dim", "G", "Am", "Bm", "C", "D"],
    "F major": ["F", "Gm", "Am", "Bb", "C", "Dm", "Edim"],
    "D minor": ["Dm", "Edim", "F", "Gm", "Am", "Bb", "C"],
    "Bb major": ["Bb", "Cm", "Dm", "Eb", "F", "Gm", "Adim"],
}


@pytest.mark.parametrize("label", sorted(KEY_CHORDS_BY_HAND))
def test_a_keys_own_chords_are_the_ones_theory_gives(label):
    signature, home = parse_browse_key(label)

    assert key_chords(signature, home) == KEY_CHORDS_BY_HAND[label]


@pytest.mark.parametrize("label", [label for label, _ in browse_keys()])
def test_every_key_gives_seven_readable_chords_all_inside_the_key(label):
    signature, home = parse_browse_key(label)
    chords = key_chords(signature, home)
    in_key = semitones_in(signature)

    assert len(chords) == 7

    for chord in chords:
        split_chord(chord)
        assert set(chord_semitones(chord)) <= in_key

    # The home chord comes first.
    assert chord_semitones(chords[0])[0] == (
        chord_semitones(home)[0]
    )


# --- the song's own keys and chords ----------------------------


def test_a_song_with_one_key_gives_one_section_of_its_distinct_chords():
    sections = song_sections("G", "| G . . . | C . . . | G . . . | D . . . |")

    assert sections == [
        {"key": "G", "from_beat": 0.0, "chords": ["G", "C", "D"]}
    ]


def test_a_chord_belongs_to_the_key_in_force_where_it_starts():
    chart = "| G . . . | C . . . | D . . . | Ab . . . | Db . . . |"

    sections = song_sections("G, Ab from beat 8", chart)

    assert sections == [
        {"key": "G", "from_beat": 0.0, "chords": ["G", "C"]},
        {"key": "Ab", "from_beat": 8.0, "chords": ["D", "Ab", "Db"]},
    ]


def test_no_song_means_browsing():
    assert song_sections("C", "") == []
    assert song_sections("C", "   ") == []
    # A key half typed, or a chart that does not read, is not
    # an error to the person typing - the sheet just browses.
    assert song_sections("G, Ab from", "| G . . . |") == []
    assert song_sections("G", "| Xyz . . . |") == []


# --- choices, defaults and what the sheet says -----------------


def test_the_song_keys_come_first_then_all_24_browsing_keys():
    offered = choices("G", "| G . . . | C . . . |")

    assert offered[0] == ("G major - from the song", "song:0")
    assert len(offered) == 1 + 24
    assert offered[1] == ("C major", "browse:C major")

    assert len(choices("G", "")) == 24


def test_it_starts_on_the_song_if_there_is_one_else_c_major():
    assert default_selection("G", "| G . . . |") == "song:0"
    assert default_selection("G", "") == "browse:C major"


def test_a_song_choice_says_the_key_came_from_the_song():
    state = resolve("song:0", "F", "| Dm . . . | Gm . . . | A . . . |")

    assert state["from_song"] is True
    assert state["signature"] == "F"
    assert state["chords"] == ["Dm", "Gm", "A"]
    assert state["line"].startswith("Key: F major, from the song.")


def test_a_second_song_key_names_the_beat_it_starts_at():
    chart = "| G . . . | C . . . | D . . . |"

    state = resolve("song:1", "G, Ab from beat 8", chart)

    assert state["signature"] == "Ab"
    assert "from beat 8" in state["line"]


def test_browsing_says_your_choice_and_names_the_songs_own_key():
    state = resolve("browse:D major", "F", "| Dm . . . | Gm . . . |")

    assert state["from_song"] is False
    assert state["chords"] == [
        "D", "Em", "F#m", "G", "A", "Bm", "C#dim"
    ]
    assert state["line"] == (
        "Key: D major, your choice. The song's own key is F major."
    )


def test_browsing_with_no_song_says_so():
    state = resolve("browse:C major", "C", "")

    assert state["line"] == "Key: C major. No song loaded - browsing."


def test_a_choice_that_no_longer_exists_falls_back_not_fails():
    # The song changed under a "song:1" selection.
    state = resolve("song:1", "G", "| G . . . | C . . . |")

    assert state["signature"] == "C"
    assert state["line"].startswith("Key: C major")

    assert resolve("nonsense", "G", "")["signature"] == "C"
    assert resolve(None, "G", "")["signature"] == "C"


